/// `common::assert_reference_geometry` is the only thing standing between a
/// drifted PyPEEC copy and a gate that compares two different problems while
/// passing. So it is itself asserted here, on a synthetic reference: one that
/// declares what the gate expects must pass, and every way of disagreeing
/// must fail *naming* what disagreed. Without this the mechanism could stop
/// checking anything and every gate above would keep going green — which is
/// precisely the failure mode it exists to close.
///
/// These run in every profile and need no PyPEEC: they are about the check,
/// not the physics.
mod reference_geometry_gate {
    use super::assert_reference_geometry;

    /// A reference declaring exactly the spiral fixture's geometry, plus an
    /// array field so the `name[i][j]` paths the plane gates use are covered.
    fn reference() -> serde_json::Value {
        serde_json::json!({
            "fixture": "spiral",
            "freq_ac_hz": 1.0e3,
            "geometry": {
                "turns": 2,
                "start_len_um": 60.0,
                "pitch_um": 15.0,
                "width_um": 2.0,
                "thickness_um": 2.0,
                "sigma_s_per_m": 5.8e7,
                "lo_m": [0.0, 0.0],
                "landings_m": [[0.1875e-3, 0.3875e-3], [1.0125e-3, 0.3875e-3]],
            },
        })
    }

    fn expected() -> Vec<(&'static str, f64)> {
        vec![
            ("turns", 2.0),
            ("start_len_um", 60.0),
            ("pitch_um", 15.0),
            ("width_um", 2.0),
            ("thickness_um", 2.0),
            ("sigma_s_per_m", 5.8e7),
            ("lo_m[0]", 0.0),
            ("lo_m[1]", 0.0),
            ("landings_m[0][0]", 0.1875e-3),
            ("landings_m[1][1]", 0.3875e-3),
        ]
    }

    #[test]
    fn an_agreeing_reference_passes() {
        assert_reference_geometry(&reference(), "spiral", 1.0e3, &expected());
    }

    #[test]
    #[should_panic(expected = "reference solved pitch_um")]
    fn a_drifted_scalar_fails_naming_the_field() {
        let mut reference = reference();
        reference["geometry"]["pitch_um"] = serde_json::json!(16.0);
        assert_reference_geometry(&reference, "spiral", 1.0e3, &expected());
    }

    #[test]
    #[should_panic(expected = "reference solved landings_m[1][1]")]
    fn a_drifted_array_element_fails_naming_its_path() {
        let mut reference = reference();
        reference["geometry"]["landings_m"][1][1] = serde_json::json!(0.4e-3);
        assert_reference_geometry(&reference, "spiral", 1.0e3, &expected());
    }

    #[test]
    #[should_panic(expected = "declares fixture \"plane\"")]
    fn the_wrong_fixture_fails() {
        let mut reference = reference();
        reference["fixture"] = serde_json::json!("plane");
        assert_reference_geometry(&reference, "spiral", 1.0e3, &expected());
    }

    #[test]
    #[should_panic(expected = "carries no `geometry` object")]
    fn a_reference_predating_the_geometry_object_fails() {
        let mut reference = reference();
        reference.as_object_mut().unwrap().remove("geometry");
        assert_reference_geometry(&reference, "spiral", 1.0e3, &expected());
    }

    #[test]
    #[should_panic(expected = "has no numeric `pitch_um`")]
    fn a_field_the_reference_never_declared_fails() {
        let mut reference = reference();
        reference["geometry"]
            .as_object_mut()
            .unwrap()
            .remove("pitch_um");
        assert_reference_geometry(&reference, "spiral", 1.0e3, &expected());
    }

    #[test]
    #[should_panic(expected = "this gate extracts")]
    fn a_reference_solved_at_another_frequency_fails() {
        let mut reference = reference();
        reference["freq_ac_hz"] = serde_json::json!(1.0e4);
        assert_reference_geometry(&reference, "spiral", 1.0e3, &expected());
    }

    /// The tolerance is a relative one, so the identical decimal literals
    /// the two languages write must agree exactly, while a float round-trip
    /// through JSON must not be read as drift.
    #[test]
    fn a_json_round_trip_is_not_drift() {
        let text = serde_json::to_string(&reference()).unwrap();
        let round_tripped: serde_json::Value = serde_json::from_str(&text).unwrap();
        assert_reference_geometry(&round_tripped, "spiral", 1.0e3, &expected());
    }
}
